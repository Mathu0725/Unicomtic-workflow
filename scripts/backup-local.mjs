import nextEnv from "@next/env";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash, randomUUID } from "node:crypto";
import path from "node:path";
nextEnv.loadEnvConfig(process.cwd(), process.env.NODE_ENV !== "production");
const url = process.env.NEXT_PUBLIC_SUPABASE_URL || "";
if (url && !/mock|dummy|your-project/.test(url)) throw new Error("Use your Supabase backup/restore procedure for live database storage. No local backup was created.");
const dir = path.resolve(process.env.DATA_DIR || ".data"), source = path.join(dir, "platform.json"), bytes = await readFile(source);
const snapshot = JSON.parse(bytes.toString("utf8"));
if (!Number.isSafeInteger(snapshot.version) || !Array.isArray(snapshot.data?.students) || !Array.isArray(snapshot.data?.registrations)) throw new Error("The source snapshot is invalid. Preserve it for recovery; no verified backup was created.");
const backupDir = path.join(dir, "backups");
await mkdir(backupDir, { recursive: true });
const name = `platform-${new Date().toISOString().replace(/[:.]/g, "-")}-${randomUUID().slice(0, 8)}.json`, target = path.join(backupDir, name);
await writeFile(target, bytes, { flag: "wx", mode: 0o600 });
const hash = value => createHash("sha256").update(value).digest("hex");
const digest = hash(bytes);
if (hash(await readFile(target)) !== digest) throw new Error("Backup verification failed. The live source was not modified.");
await writeFile(`${target}.sha256`, `${digest}  ${name}\n`, { flag: "wx", mode: 0o600 });
console.log(JSON.stringify({ verified: true, path: target, version: snapshot.version, bytes: bytes.length }));
